/**
 * 内置面具（builtin persona masks）
 *
 * 设计目标：提供"可复用人格包"——头像 + 名字 + 人格指令 + 预设对话示例（few-shot），
 * 选中后整个对话以该人格进行。与 `./style-presets.ts` 的风格预设正交：
 *   面具 = 人格层（我是谁），风格 = 语气层（怎么说），两者叠加注入 system prompt。
 *
 * P0 仅代码内置（不入库、只读、不可编辑）；`Conversation.maskId` 直接存本文件的 id。
 * P1 用户自定义面具入库时，用 `user:<cuid>` 前缀与内置 id 区分。
 *
 * few-shot 的价值：用 2-4 轮示例对话锚定交互格式（输出结构、追问节奏），
 * 这是纯 systemPrompt 文字描述难以稳定表达的，也是面具区别于风格预设的核心。
 */

import { BUILTIN_MASK_LIBRARY } from './builtin-masks-library'
import { BUILTIN_GAMES } from './builtin-games'
import { DEAI_WRITING_DISCIPLINE } from '@/lib/text/deai'

export interface BuiltinMaskFewShotTurn {
  role: 'user' | 'assistant'
  content: string
}

export interface BuiltinMask {
  id: string
  /** 中文显示名 */
  name: string
  /** emoji 头像，单字符 */
  avatar: string
  /** 一句话定位，写在选择器卡片副标题 */
  description: string
  /** 注入到 system prompt 最前面的人格段落 */
  systemPrompt: string
  /** 预设对话示例，插在 system 之后、真实消息之前 */
  fewShot: BuiltinMaskFewShotTurn[]
  /** 可选：该面具默认对话风格；仅当 body/DB 均未显式指定风格时生效 */
  stylePreset?: string
  /** 可选:学科倾向(如 math),知识库检索工具(search_knowledge)的默认过滤建议(半绑定,
   *  不锁死:用户问其他学科时模型可不带 subject 查全部)。自定义面具暂无此字段。 */
  subject?: string
  /** 可选:标记为「游戏」面具(世界引擎型人格)。chat/route.ts 据此开干净车道——
   *  关掉记忆注入、回复长度限制、课本检索、练题与澄清工具,避免学习脚手架污染沉浸叙事。
   *  仅内置游戏面具携带(见 ./builtin-games.ts),自定义面具暂无此字段。 */
  kind?: 'game'
}

/** 通过 id 查内置面具；未命中返回 undefined（供 API 校验与前端解析） */
export function getBuiltinMask(id: string | null | undefined): BuiltinMask | undefined {
  if (!id) return undefined
  return (
    BUILTIN_MASKS.find((m) => m.id === id) ??
    BUILTIN_MASK_LIBRARY.find((m) => m.id === id) ??
    BUILTIN_GAMES.find((m) => m.id === id)
  )
}

